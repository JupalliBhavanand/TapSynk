function load(file, mocks = {}, globals = {}) {
  if (file === 'src/lib/agent.ts') mocks['@/lib/business-identity'] = load('src/lib/business-identity.ts');
  const mod = { exports: {} };
  const source = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  vm.runInNewContext(source, { module: mod, exports: mod.exports, require: name => name in mocks ? mocks[name] : require(name), process: { env: {} }, Intl, Date, AbortSignal, console, ...globals });
  return mod.exports;
}
